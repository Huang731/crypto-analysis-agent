    async def test_summarize_history_preserves_recent_messages(
        self, history_messages: list[AnyMessage], report: str
    ) -> None:
        question = history_messages[-1].content
        assert isinstance(question, str)
        state = RoutingState(
            messages=history_messages,
            scope={},
            resolved_question=question,
            route="",
            report=report,
        )
        summarize_history = make_summarize_history()
        result = await summarize_history(state)
        messages = result["messages"]

        assert len(messages) == 3
        assert isinstance(messages[0], HumanMessage)
        content = messages[0].content
        assert isinstance(content, str)
        assert content.startswith("[之前的对话摘要] ")
        summary = content.removeprefix("[之前的对话摘要] ").strip()
        print(f"\n本轮问题：{question}\n生成摘要：{summary}\n摘要字数：{len(summary)}")
        assert summary
        assert len(summary) <= 100
        # 最近的用户问题和本轮报告应保持原文，不进入本轮压缩。
        assert messages[-2:] == [history_messages[-1], AIMessage(content=report)]
