"""RAG 图片提取与看图问答的提示词。"""

DESCRIBE_IMAGE_PROMPT = """请仔细分析这张图片，提取结构化信息用于知识库检索。要求：
1. 图表类型（柱状图/折线图/饼图/表格/示意图/其他）
2. 所有能读到的数值和它们对应的标签（如「Q1: 1800」「Q2: 2400」）
3. 坐标轴标签和单位
4. 关键趋势或对比结论（如「Q4 最高」「逐季上升」）
5. 如果是示意图/流程图，描述其中的文字和结构关系

用简洁的条目列出，不要写「这是一张...」式的废话开头。直接给数据和结论。"""


def answer_with_image_prompt(question: str) -> str:
    """根据问题生成看图问答的用户提示词。"""
    return f"请根据图片回答：{question}。直接给答案，简明扼要。"
